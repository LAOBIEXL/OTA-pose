class SinusoidalPositionEmbeddings(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.dim = dim

    def forward(self, time):
        device = time.device
        half_dim = self.dim // 2
        embeddings = math.log(10000) / (half_dim - 1)
        embeddings = torch.exp(torch.arange(half_dim, device=device) * -embeddings)
        embeddings = time[:, None] * embeddings[None, :]
        embeddings = torch.cat((embeddings.sin(), embeddings.cos()), dim=-1)
        return embeddings


def drop_path(x, drop_prob: float = 0., training: bool = False, scale_by_keep: bool = True):
    """Drop paths (Stochastic Depth) per sample (when applied in main path of residual blocks).

    This is the same as the DropConnect impl I created for EfficientNet, etc networks, however,
    the original name is misleading as 'Drop Connect' is a different form of dropout in a separate paper...
    See discussion: https://github.com/tensorflow/tpu/issues/494#issuecomment-532968956 ... I've opted for
    changing the layer and argument names to 'drop path' rather than mix DropConnect as a layer name and use
    'survival rate' as the argument.

    """
    if drop_prob == 0. or not training:
        return x
    keep_prob = 1 - drop_prob
    shape = (x.shape[0],) + (1,) * (x.ndim - 1)  # work with diff dim tensors, not just 2D ConvNets
    random_tensor = x.new_empty(shape).bernoulli_(keep_prob)
    if keep_prob > 0.0 and scale_by_keep:
        random_tensor.div_(keep_prob)
    return x * random_tensor

def modulate(x, scale , shift):
    return x * (1 + scale.unsqueeze(1)) + shift.unsqueeze(1)


def _ntuple(n):
    def parse(x):
        if isinstance(x, collections.abc.Iterable) and not isinstance(x, str):
            return x
        return tuple(repeat(x, n))

    return parse


to_1tuple = _ntuple(1)
to_2tuple = _ntuple(2)
to_3tuple = _ntuple(3)
to_4tuple = _ntuple(4)
to_ntuple = _ntuple


def _trunc_normal_(tensor, mean, std, a, b):
    # Cut & paste from PyTorch official master until it's in a few official releases - RW
    # Method based on https://people.sc.fsu.edu/~jburkardt/presentations/truncated_normal.pdf
    def norm_cdf(x):
        # Computes standard normal cumulative distribution function
        return (1. + math.erf(x / math.sqrt(2.))) / 2.

    if (mean < a - 2 * std) or (mean > b + 2 * std):
        warnings.warn("mean is more than 2 std from [a, b] in nn.init.trunc_normal_. "
                      "The distribution of values may be incorrect.",
                      stacklevel=2)

    # Values are generated by using a truncated uniform distribution and
    # then using the inverse CDF for the normal distribution.
    # Get upper and lower cdf values
    l = norm_cdf((a - mean) / std)
    u = norm_cdf((b - mean) / std)

    # Uniformly fill tensor with values from [l, u], then translate to
    # [2l-1, 2u-1].
    tensor.uniform_(2 * l - 1, 2 * u - 1)

    # Use inverse cdf transform for normal distribution to get truncated
    # standard normal
    tensor.erfinv_()

    # Transform to proper mean, std
    tensor.mul_(std * math.sqrt(2.))
    tensor.add_(mean)

    # Clamp to ensure it's in the proper range
    tensor.clamp_(min=a, max=b)
    return tensor


def trunc_normal_(tensor, mean=0., std=1., a=-2., b=2.):
    # type: (Tensor, float, float, float, float) -> Tensor
    r"""Fills the input Tensor with values drawn from a truncated
    normal distribution. The values are effectively drawn from the
    normal distribution :math:`\mathcal{N}(\text{mean}, \text{std}^2)`
    with values outside :math:`[a, b]` redrawn until they are within
    the bounds. The method used for generating the random values works
    best when :math:`a \leq \text{mean} \leq b`.

    NOTE: this impl is similar to the PyTorch trunc_normal_, the bounds [a, b] are
    applied while sampling the normal with mean/std applied, therefore a, b args
    should be adjusted to match the range of mean, std args.

    Args:
        tensor: an n-dimensional `torch.Tensor`
        mean: the mean of the normal distribution
        std: the standard deviation of the normal distribution
        a: the minimum cutoff value
        b: the maximum cutoff value
    Examples:
        >>> w = torch.empty(3, 5)
        >>> nn.init.trunc_normal_(w)
    """
    with torch.no_grad():
        return _trunc_normal_(tensor, mean, std, a, b)


class DropPath(nn.Module):
    """Drop paths (Stochastic Depth) per sample  (when applied in main path of residual blocks).
    """

    def __init__(self, drop_prob=None):
        super(DropPath, self).__init__()
        self.drop_prob = drop_prob

    def forward(self, x):
        return drop_path(x, self.drop_prob, self.training)

    def extra_repr(self):
        return 'p={}'.format(self.drop_prob)


class Mlp(nn.Module):
    def __init__(self, in_features, hidden_features=None, out_features=None, act_layer=nn.GELU, drop=0.):
        super().__init__()
        out_features = out_features or in_features
        hidden_features = hidden_features or in_features
        self.fc1 = nn.Linear(in_features, hidden_features)
        self.act = act_layer()
        self.fc2 = nn.Linear(hidden_features, out_features)
        self.drop = nn.Dropout(drop)

    def forward(self, x):
        x = self.fc1(x)
        x = self.act(x)
        x = self.fc2(x)
        x = self.drop(x)
        return x


class Attention(nn.Module):
    def __init__(
            self, dim, num_heads=8, qkv_bias=False, qk_scale=None, attn_drop=0.,
            proj_drop=0., attn_head_dim=None, ):
        super().__init__()
        self.num_heads = num_heads
        head_dim = dim // num_heads
        self.dim = dim

        if attn_head_dim is not None:
            head_dim = attn_head_dim
        all_head_dim = head_dim * self.num_heads

        self.scale = qk_scale or head_dim ** -0.5

        self.qkv = nn.Linear(dim, all_head_dim * 3, bias=qkv_bias)

        self.attn_drop = nn.Dropout(attn_drop)
        self.proj = nn.Linear(all_head_dim, dim)
        self.proj_drop = nn.Dropout(proj_drop)

    def forward(self, x):
        B, N, C = x.shape
        qkv = self.qkv(x)
        qkv = qkv.reshape(B, N, 3, self.num_heads, -1).permute(2, 0, 3, 1, 4)
        q, k, v = qkv[0], qkv[1], qkv[2]  # make torchscript happy (cannot use tensor as tuple)

        q = q * self.scale
        attn = (q @ k.transpose(-2, -1))

        attn = attn.softmax(dim=-1)
        attn = self.attn_drop(attn)

        x = (attn @ v).transpose(1, 2).reshape(B, N, -1)
        x = self.proj(x)
        x = self.proj_drop(x)

        return x

class CrossAttention(nn.Module):
    def __init__(self, q_dim, kv_dim , heads=12, dim_head=None , dropout = 0.0):
        super().__init__()

        self.heads = heads
        self.dim_head = q_dim//heads if dim_head is None else dim_head

        hidden_dim = self.dim_head * self.heads

        self.to_q = nn.Linear(q_dim , hidden_dim)
        self.to_k = nn.Linear(kv_dim , hidden_dim)
        self.to_v = nn.Linear(kv_dim , hidden_dim)

        self.scale = self.dim_head ** -0.5

        self.to_out = nn.Linear(hidden_dim , q_dim)
        self.dropout = nn.Dropout(dropout)

    def forward(self, query, key, value, attn_mask=None):
        b, n , d = query.shape

        q = self.to_q(query)
        k = self.to_k(key)
        v = self.to_v(value)

        q, k, v = map(
            lambda t: rearrange(t, "b n (h d) -> b h n d", h=self.heads), (q , k , v)
        )
        q = q * self.scale

        sim = einsum("b h i d, b h j d -> b h i j", q, k)
        sim = sim - torch.max(sim, dim=-1, keepdim=True)[0].detach()
        # sim = sim - sim.amax(dim=-1, keepdim=True).detach()
        if attn_mask is not None:
            sim.masked_fill_(attn_mask == 0, float("-inf"))  # 将mask为0的位置填充为负无穷，使得softmax后为0
        attn = sim.softmax(dim=-1)
        attn = self.dropout(attn)

        out = einsum("b h i d, b h d j -> b h i j", attn, v)
        out = rearrange(out, "b h n d -> b n (h d)", h=self.heads)
        out = self.to_out(out)
        return out

class CrossBlock(nn.Module):

    def __init__(self, dim , cond_dim , t_dim , num_heads, mlp_ratio=4., qkv_bias=False, qk_scale=None,
                 drop=0., attn_drop=0., drop_path=0., act_layer=nn.GELU,
                 norm_layer=nn.LayerNorm, attn_head_dim=None
                 ):
        super().__init__()

        self.norm1 = norm_layer(dim)
        self.attn = Attention(
            dim, num_heads=num_heads, qkv_bias=qkv_bias, qk_scale=qk_scale,
            attn_drop=attn_drop, proj_drop=drop, attn_head_dim=attn_head_dim
        )

        self.t_mlp = (
            nn.Sequential(SiLU(), nn.Linear(t_dim, dim * 4))
        )

        self.norm2 = norm_layer(dim)
        self.cross_attn = CrossAttention(dim, cond_dim , heads=num_heads, dim_head=attn_head_dim , dropout = attn_drop)

        # NOTE: drop path for stochastic depth, we shall see if this is better than dropout here
        self.drop_path = DropPath(drop_path) if drop_path > 0. else nn.Identity()

        self.norm3 = norm_layer(dim)
        mlp_hidden_dim = int(dim * mlp_ratio)
        self.mlp = Mlp(in_features=dim, hidden_features=mlp_hidden_dim, act_layer=act_layer, drop=drop)

    def forward(self, x , condition , t):


        t = self.t_mlp(t)
        scale1, shift1 ,scale2, shift2= t.chunk(4, dim=1)


        x = x + self.drop_path(self.attn(modulate(self.norm1(x) , scale1 , shift1)))


        x = x + self.drop_path(self.cross_attn(self.norm2(x) , condition , condition))

        x = x + self.drop_path(self.mlp(modulate(self.norm3(x) , scale2 , shift2)))
        return x


class PatchEmbed(nn.Module):
    """ Image to Patch Embedding
    """

    def __init__(self, img_size=224, patch_size=4, in_chans=17, embed_dim=768, ratio=1):
        super().__init__()
        img_size = to_2tuple(img_size)
        patch_size = to_2tuple(patch_size)
        num_patches = (img_size[1] // patch_size[1]) * (img_size[0] // patch_size[0]) * (ratio ** 2)
        self.patch_shape = (int(img_size[0] // patch_size[0] * ratio), int(img_size[1] // patch_size[1] * ratio))
        self.origin_patch_shape = (int(img_size[0] // patch_size[0]), int(img_size[1] // patch_size[1]))
        self.img_size = img_size
        self.patch_size = patch_size
        self.num_patches = num_patches

        self.proj = nn.Conv2d(in_chans, embed_dim, kernel_size=patch_size, stride=(patch_size[0] // ratio),
                              padding=0)


    def forward(self, x, **kwargs):
        B, C, H, W = x.shape
        x = self.proj(x)
        Hp, Wp = x.shape[2], x.shape[3]

        x = x.flatten(2).transpose(1, 2)
        return x, (Hp, Wp)





class CADD(nn.Module):
    def __init__(self,
                 img_size=224, patch_size=16, in_chans=17, embed_dim=768, depth=12, cond_dim = 768 ,
                 num_heads=12, mlp_ratio=4., qkv_bias=False, qk_scale=None, drop_rate=0., attn_drop_rate=0.,
                 drop_path_rate=0.,  norm_layer=None,
                 ratio=1, last_norm=True,
                 patch_padding='pad',
                 deconv1_chans=768,deconv2_chans=256 , deconv3_chans=256,out_chans=17,
                 ):
        super(CADD, self).__init__()
        # Protect mutable default arguments

        norm_layer = norm_layer or partial(nn.LayerNorm, eps=1e-6)
        self.num_features = self.embed_dim = embed_dim  # num_features for consistency with other models
        self.patch_padding = patch_padding
        self.depth = depth


        # time embeddings
        time_dim = embed_dim

        self.time_mlp = nn.Sequential(
            SinusoidalPositionEmbeddings(embed_dim//2),
            nn.Linear(embed_dim//2, time_dim),
            nn.GELU(),
            nn.Linear(time_dim, time_dim),
        )

        self.patch_embed = PatchEmbed(
            img_size=img_size, patch_size=patch_size, in_chans=in_chans, embed_dim=embed_dim, ratio=ratio)
        num_patches = self.patch_embed.num_patches

        # since the pretraining model has class token
        self.pos_embed = nn.Parameter(torch.zeros(1, num_patches + 1, embed_dim))

        dpr = [x.item() for x in torch.linspace(0, drop_path_rate, depth)]  # stochastic depth decay rule

        self.blocks = nn.ModuleList([
            CrossBlock(
                dim=embed_dim, cond_dim=cond_dim , t_dim=time_dim , num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                drop=drop_rate, attn_drop=attn_drop_rate, drop_path=dpr[i], norm_layer=norm_layer,
            )
            for i in range(depth)])

        self.last_norm = norm_layer(embed_dim) if last_norm else nn.Identity()

        if self.pos_embed is not None:
            trunc_normal_(self.pos_embed, std=.02)

        self.deconv_layers = nn.Sequential(
            nn.ConvTranspose2d(in_channels = deconv1_chans, out_channels=deconv2_chans,
                               kernel_size=4, stride=2, padding=1,
                               output_padding=0, bias=False),
            nn.GroupNorm(4 , deconv2_chans),
            nn.ReLU(inplace=True),
            nn.ConvTranspose2d(in_channels=deconv2_chans, out_channels=deconv3_chans,
                               kernel_size=4, stride=2, padding=1,
                               output_padding=0, bias=False),
            nn.GroupNorm(4 , deconv3_chans),
            nn.ReLU(inplace=True),
        )
        self.fusion_difference_htms_curr_conv = CHAIN_RSB_BLOCKS(deconv3_chans * 2 ,
                                                                 deconv3_chans, 2)

        final_layer = []
        final_layer.append(nn.Conv2d(in_channels=deconv3_chans,
                                     out_channels=out_chans,
                                     kernel_size=1,
                                     stride=1,
                                     padding=0
                                     ))

        self.final_layer = final_layer[0]

    def freeze_weight(self):
        for module in self.modules():
            parameters = module.parameters()
            for parameter in parameters:
                parameter.requires_grad = False

    def init_weights(self, ):
        """Initialize the weights in backbone.
        Args:
            pretrained (str, optional): Path to pre-trained weights.
                Defaults to None.
        """

        def basic_init(module):
            if isinstance(module, nn.Linear):
                torch.nn.init.xavier_uniform_(module.weight)
                if module.bias is not None:
                    nn.init.constant_(module.bias, 0)
            elif isinstance(module, nn.LayerNorm):
                nn.init.constant_(module.bias, 0)
                nn.init.constant_(module.weight, 1.0)

        self.apply(basic_init)


        nn.init.xavier_uniform_(self.patch_embed.proj.weight)
        nn.init.constant_(self.patch_embed.proj.bias, 0)


        # Zero-out adaLN modulation layers in DiT blocks:
        for block in self.blocks:
            nn.init.constant_(block.t_mlp[-1].weight, 0)
            nn.init.constant_(block.t_mlp[-1].bias, 0)





    def get_num_layers(self):
        return len(self.blocks)

    @torch.jit.ignore
    def no_weight_decay(self):
        return {'pos_embed', 'cls_token'}

    def forward_features(self, x , condition , t, feat_backbone):
        B, C, H, W = x.shape
        x = x.cuda()
        x, (Hp, Wp) = self.patch_embed(x)

        t = self.time_mlp(t)

        if self.pos_embed is not None:
            # fit for multiple GPU training
            # since the first element for pos embed (sin-cos manner) is zero, it will cause no difference
            x = x + self.pos_embed[:, 1:] + self.pos_embed[:, :1]

        # for blk in self.blocks:
        #     x = blk(x , condition ,t)

        block_outputs = []
        for i in range(self.depth):
            if i == 0:
                x = self.blocks[i](x, condition ,t)
            elif i > self.depth/2:
                skip_connection = block_outputs[self.depth-i-1]
                x = self.blocks[i](block_outputs[-1] + skip_connection, condition ,t)
            else:
                x = self.blocks[i](block_outputs[-1], condition ,t)
            block_outputs.append(x)

        x = self.last_norm(x)

        xp = x.permute(0, 2, 1).reshape(B, -1, Hp, Wp).contiguous()

        xp = self.deconv_layers(xp)


        xp = self.fusion_difference_htms_curr_conv(torch.cat([xp,feat_backbone], dim=1))

        xp = self.final_layer(xp)


        return xp

    def forward(self, x, time, x_self_cond,feat_backbone=None):
        x = self.forward_features(x , x_self_cond , time, feat_backbone)
        return x




